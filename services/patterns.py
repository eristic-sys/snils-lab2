"""Регулярные выражения для СНИЛС."""
import re

# Формат: XXX-XXX-XXX YY (допускаем и дефис перед контрольным числом).
# (?<!\d) и (?!\d) не дают вырезать СНИЛС из более длинной цепочки цифр.
SNILS_SEARCH = re.compile(r"(?<!\d)\d{3}-\d{3}-\d{3}[ -]\d{2}(?!\d)")

# Для проверки строки целиком (используется с fullmatch).
SNILS_FULL = re.compile(r"\d{3}-\d{3}-\d{3}[ -]\d{2}")